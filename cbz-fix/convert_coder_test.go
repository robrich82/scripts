func TestImageCoder(t *testing.T) {
	cases := []struct {
		name string
		data []byte
		want string
	}{
		{"gif87", []byte("GIF87a...."), "gif"},
		{"gif89", []byte("GIF89a...."), "gif"},
		{"webp", fakeNonImage(), "webp"},
		{"riff not webp", []byte("RIFF\x00\x00\x00\x00WAVEfmt "), ""},
		{"bmp", []byte("BM\x00\x00"), "bmp"},
		{"tiff le", []byte("II*\x00...."), "tiff"},
		{"tiff be", []byte("MM\x00*...."), "tiff"},
		{"bigtiff", []byte("II+\x00...."), "tiff"},
		{"jxl codestream", []byte{0xFF, 0x0A, 0x00}, "jxl"},
		{"jxl container", []byte("\x00\x00\x00\x0cJXL \r\n\x87\n"), "jxl"},
		{"avif", []byte("\x00\x00\x00\x1cftypavif\x00\x00\x00\x00"), "avif"},
		{"heic", []byte("\x00\x00\x00\x18ftypheic\x00\x00\x00\x00"), "heic"},
		{"mp4", []byte("\x00\x00\x00\x18ftypisom\x00\x00\x00\x00"), ""},
		{"svg", []byte(`<svg xmlns="http://www.w3.org/2000/svg"/>`), ""},
		{"xml svg", []byte(`<?xml version="1.0"?><svg/>`), ""},
		{"mvg", []byte("viewbox 0 0 4 4\n"), ""},
		{"text", []byte("hello"), ""},
		{"empty", nil, ""},
	}
	for _, tc := range cases {
		if got := imageCoder(tc.data); got != tc.want {
			t.Errorf("imageCoder(%s) = %q, want %q", tc.name, got, tc.want)
		}
	}
}

// An SVG page can make ImageMagick read a local file into its output, so it
// must fail before ImageMagick runs and leave the CBZ untouched.
func TestProcessCBZ_RejectsSVGDisguisedAsPage(t *testing.T) {
	secret := filepath.Join(t.TempDir(), "secret.png")
	if err := os.WriteFile(secret, portrait, 0o644); err != nil {
		t.Fatal(err)
	}
	svg := []byte(`<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="4" height="4">` +
		`<image xlink:href="file:///` + filepath.ToSlash(secret) + `" width="4" height="4"/></svg>`)

	path := makeCBZ(t, []zipEntry{
		{"001.webp", svg},
		{"002.png", portrait},
	})
	before, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}

	_, err = processCBZ(path, false, false, false, true, false)
	if err == nil || !strings.Contains(err.Error(), "unrecognised image format") {
		t.Fatalf("processCBZ error = %v, want unrecognised image format", err)
	}
	if after, _ := os.ReadFile(path); !bytes.Equal(before, after) {
		t.Error("CBZ was rewritten despite the rejected page")
	}
}

// Each supported format, generated by the local ImageMagick, converts through
// its named coder. Formats this ImageMagick build can't encode are skipped.
func TestMagickToPNG_RealFormats(t *testing.T) {
	if _, err := exec.LookPath(magickBin); err != nil {
		t.Skip("ImageMagick not installed")
	}
	for _, format := range []string{"gif", "webp", "bmp", "tiff", "jxl", "avif", "heic"} {
		t.Run(format, func(t *testing.T) {
			src, err := exec.Command(magickBin, "-size", "8x6", "xc:red", format+":-").Output()
			if err != nil || len(src) == 0 {
				t.Skipf("this ImageMagick can't encode %s: %v", format, err)
			}
			if got := imageCoder(src); got != format {
				t.Fatalf("imageCoder = %q, want %q", got, format)
			}
			out, err := magickToPNG(src)
			if err != nil {
				t.Fatalf("magickToPNG: %v", err)
			}
			img, err := png.Decode(bytes.NewReader(out))
			if err != nil {
				t.Fatalf("output is not a PNG: %v", err)
			}
			if b := img.Bounds(); b.Dx() != 8 || b.Dy() != 6 {
				t.Errorf("size = %dx%d, want 8x6", b.Dx(), b.Dy())
			}
		})
	}
}
